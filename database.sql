CREATE DATABASE IF NOT EXISTS `colegio_asistencia` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `colegio_asistencia`;

-- 1. Tabla de Usuarios (Administradores / Personal de Control)
CREATE TABLE IF NOT EXISTS `usuarios` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `usuario` VARCHAR(50) NOT NULL UNIQUE,
  `clave` VARCHAR(255) NOT NULL,
  `nombre_completo` VARCHAR(100) NOT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. Tabla de Configuración de la Institución
CREATE TABLE IF NOT EXISTS `configuracion` (
  `id` INT PRIMARY KEY,
  `nombre_colegio` VARCHAR(150) NOT NULL DEFAULT 'Colegio Ricardo Bentin Grande',
  `hora_limite` TIME NOT NULL DEFAULT '08:00:00',
  `total_dias` INT NOT NULL DEFAULT 1,
  `logo_url` TEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. Tabla de Estudiantes (Total: 564 estudiantes)
CREATE TABLE IF NOT EXISTS `estudiantes` (
  `dni` VARCHAR(25) PRIMARY KEY,
  `nombre` VARCHAR(150) NOT NULL,
  `grado` VARCHAR(20) NOT NULL,
  `seccion` VARCHAR(10) NOT NULL,
  `foto` LONGTEXT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. Tabla de Asistencias Diarias
CREATE TABLE IF NOT EXISTS `asistencias` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `estudiante_dni` VARCHAR(25) NOT NULL,
  `fecha` DATE NOT NULL,
  `hora` TIME NOT NULL,
  `estado` ENUM('Presente', 'Tarde', 'Ausente') NOT NULL DEFAULT 'Presente',
  `justificacion` TEXT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY `uk_estudiante_fecha` (`estudiante_dni`, `fecha`),
  CONSTRAINT `fk_asistencias_estudiante` FOREIGN KEY (`estudiante_dni`) 
    REFERENCES `estudiantes` (`dni`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. Tabla de Profesores / Directorio Docente
CREATE TABLE IF NOT EXISTS `profesores` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `dni` VARCHAR(15) NOT NULL UNIQUE,
  `nombre_completo` VARCHAR(120) NOT NULL,
  `especialidad` VARCHAR(100) NOT NULL,
  `foto` TEXT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 6. Tabla de Excepciones de Calendario (Feriados / Sin Clases)
CREATE TABLE IF NOT EXISTS `calendario_excepciones` (
  `fecha` DATE PRIMARY KEY,
  `tipo` ENUM('feriado', 'sin_clases') NOT NULL,
  `motivo` VARCHAR(255) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

